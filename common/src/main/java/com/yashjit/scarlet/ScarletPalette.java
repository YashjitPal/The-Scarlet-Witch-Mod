package com.yashjit.scarlet;

/**
 * The chaos magic palette from the design document. Every color in the mod derives from these.
 */
public final class ScarletPalette {

    public static final int CORE = 0xFFE6EC;
    public static final int PINK = 0xFF8C9E;
    public static final int BRIGHT_SCARLET = 0xFF3355;
    public static final int SCARLET = 0xE0143C;
    public static final int CRIMSON = 0xA50D2C;
    public static final int WINE = 0x5C0717;
    public static final int SHADOW = 0x1C0307;
    /** The filter of scarlet glass: what of each color passes through it. */
    public static final int GLASS = 0xFF1A26;

    /** What the Darkhold's corruption pulls magic toward: black-crimson, with sickly highlights. */
    public static final int SICKLY = 0x9B1B30;
    public static final int ABYSS = 0x3A0010;
    public static final int VOID = 0x0B0004;

    private ScarletPalette() {
    }
}
